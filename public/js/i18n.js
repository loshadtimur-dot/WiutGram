const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
const SKIP = [
  '.msg__text',
  '.post-card__caption',
  '.profile-bio__text',
  '.chat-row__name',
  '.unbox__title h2',
  '.sidebar__profile-name',
  '[data-no-i18n]',
  'script',
  'style'
].join(',');

let lang = 'ru';
let observer = null;

function normalize(value) {
  return String(value || '').replace(/\s+/g, ' ').trim();
}

function translate(value) {
  if (lang !== 'en') return null;
  const key = normalize(value);
  if (!key) return null;
  let hit = DICT[key];
  if (!hit) {
    // Labels often start with an emoji: "🎧 Музыка". Keep the emoji, translate the word.
    const emoji = /^(\p{Extended_Pictographic}\uFE0F?\s*)(.+)$/u.exec(key);
    if (emoji && DICT[emoji[2]]) hit = `${emoji[1]}${DICT[emoji[2]]}`;
  }
  if (!hit) {
    for (const [pattern, build] of PATTERNS) {
      const match = pattern.exec(key);
      if (match) {
        hit = build(match);
        break;
      }
    }
  }
  if (!hit) return null;
  const lead = String(value).match(/^\s*/)[0];
  const trail = String(value).match(/\s*$/)[0];
  return `${lead}${hit}${trail}`;
}

function shouldSkip(node) {
  const parent = node.nodeType === 1 ? node : node.parentElement;
  if (!parent) return true;
  return !!parent.closest(SKIP);
}

function translateTextNode(node) {
  if (shouldSkip(node)) return;
  if (node.__wgOriginal === undefined) node.__wgOriginal = node.nodeValue;
  if (node.__wgOriginal === null) return;
  const next = translate(node.__wgOriginal);
  if (next === null) return;
  if (node.nodeValue !== next) node.nodeValue = next;
}

function walk(root) {
  if (!root) return;
  if (root.nodeType === 3) {
    translateTextNode(root);
    return;
  }
  if (root.nodeType !== 1) return;
  if (root.matches(SKIP)) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node);
    node = walker.nextNode();
  }
  if (root.attributes) translateAttributes(root);
  const all = root.querySelectorAll('[placeholder], [title], [aria-label], [alt]');
  for (const node2 of all) translateAttributes(node2);
}

function translateAttributes(node) {
  if (!node || node.nodeType !== 1 || node.closest(SKIP)) return;
  for (const name of ATTRS) {
    if (!node.hasAttribute(name)) continue;
    if (!node.__wgAttr) node.__wgAttr = {};
    if (node.__wgAttr[name] === undefined) node.__wgAttr[name] = node.getAttribute(name);
    const original = node.__wgAttr[name];
    const next = translate(original);
    if (next !== null && node.getAttribute(name) !== next) node.setAttribute(name, next);
  }
}

export function getLang() {
  return lang;
}

export function t(value) {
  return translate(value) || value;
}

export function initI18n() {
  const stored = localStorage.getItem(LANG_KEY);
  lang = stored === 'en' ? 'en' : 'ru';
  document.documentElement.lang = lang;
  document.documentElement.classList.toggle('lang-en', lang === 'en');
  if (lang !== 'en' || !document.body) return;
  walk(document.body);
  if (observer) observer.disconnect();
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') {
        translateTextNode(record.target);
      } else if (record.type === 'attributes') {
        translateAttributes(record.target);
      } else {
        for (const node of record.addedNodes) walk(node);
      }
    }
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRS
  });
}

export function setLang(next) {
  localStorage.setItem(LANG_KEY, next === 'en' ? 'en' : 'ru');
  window.location.reload();
}

export function langToggle() {
  return lang === 'en' ? 'RU' : 'EN';
}
