export default function LegalPage(ctx) {
  const kind = ctx.props.kind === 'privacy' ? 'privacy' : 'rules';
  const content = kind === 'privacy' ? PRIVACY : RULES;
  const root = el('div', { class: 'legal' });

  const back = el('a', { class: 'legal__back', attrs: { href: getState().user ? '/settings' : '/' } });
  back.append(svgIcon('arrowLeft', { size: 16 }));
  back.append(el('span', { text: getState().user ? 'К настройкам' : 'На главную' }));
  root.append(back);

  const card = el('div', { class: 'legal__card' });
  card.append(el('h1', { text: content.title }));
  card.append(el('div', { class: 'legal__updated', text: content.updated }));
  const article = el('article');
  article.append(el('p', { text: content.intro }));
  for (const section of content.sections) {
    article.append(el('h2', { text: section.title }));
    if (section.paragraphs) {
      for (const paragraph of section.paragraphs) article.append(el('p', { text: paragraph }));
    }
    if (section.list) {
      const list = el('ul');
      for (const item of section.list) list.append(el('li', { text: item }));
      article.append(list);
    }
  }
  card.append(article);
  root.append(card);

  const switcher = el('div', { class: 'row' });
  const here = el('span', { class: 'tag', text: '18+ · Wiutgram' });
  switcher.append(here);
  switcher.append(
    el('a', {
      class: 'btn btn-secondary btn-sm',
      text: kind === 'privacy' ? 'Правила сообщества' : 'Политика конфиденциальности',
      attrs: { href: kind === 'privacy' ? '/rules' : '/privacy' }
    })
  );
  root.append(switcher);

  return root;
}
